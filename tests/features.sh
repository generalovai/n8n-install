#!/usr/bin/env bash
# Проверяет, что важные возможности не пропали из скриптов при правках.
# Такое уже случалось: при переписывании ротации молча исчезло
# предупреждение о нехватке места.
set -Eeuo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
I="$ROOT/install.sh"
fail=0

need() {  # need "что ищем" "описание"
  grep -q -- "$1" "$I" || { echo "  ПРОПАЛО: $2"; fail=1; }
}

# уведомления
need 'Заканчивается место на диске'   'предупреждение о нехватке места'
need 'Не удалось сделать резервную копию' 'сообщение о неудачной копии'
need 'n8n не отвечает'                'тревога сторожа'
need 'n8n снова работает'             'сообщение о восстановлении'
need 'n8n обновлён'                   'сообщение об обновлении'
need 'Обновление не удалось'          'сообщение об откате'
need 'Ежемесячная сводка'             'ежемесячная сводка'
need 'n8n установлен и работает'      'сообщение об окончании установки'
need 'parse_mode=HTML'                'разметка сообщений'

# обслуживание
need '=== ПРОКСИ ==='                 'проверка прокси в diagnose.sh'
need 'закончилась оплата прокси'      'подсказка в diagnose.sh, если прокси умер'
need 'NO_PROXY_EXTRA'                 'обход прокси для Telegram, если прокси его закрывает'
need 'heartbeat "$PULL_PID"'          'на скачивании образов пишет, что работа идёт'
need 'ждём сертификат, прошло'        'на ожидании сертификата пишет, сколько прошло'
need 'набрана в русской раскладке'    'распознаёт русские буквы в адресе'
need 'if layout_mixup "$FQDN"; then'   'проверяет и адрес, сохранённый с прошлого раза'
need 'в интернете не найден'            'говорит, что не найден сам домен, а не запись'
need 'for srv in 1.1.1.1 8.8.8.8'      'запасной DNS-сервер для проверки записи'
need 'открывается через раз'           'честно говорит, что Telegram с сервера работает через раз'
need 'tg_ok --resolve'                  'проверяет каждый адрес Telegram, а не один запрос'
need 'send --proxy "$PROXY"'            'уведомления идут через прокси'
need 'for try in 1 2 3'                 'уведомления повторяются до трёх раз'
need '=== TELEGRAM ==='                 'блок Telegram в diagnose.sh'
need 'это большое обновление, само не ставим' 'автообновление не перескакивает на новую большую версию n8n'
need 'Оставляем вашу версию n8n'        'повторный запуск установщика не перескакивает на новую большую версию'
need 'rotate "db-"'                   'ротация копий'
need 'gunzip -t'                      'проверка копии перед восстановлением'
need 'before-restore'                 'страховочная копия перед восстановлением'
need 'update-in-progress'             'молчание сторожа во время обновления'
need 'max-size'                       'ограничение логов контейнеров'
need 'logrotate.d/n8n'                'ротация логов скриптов'
need 'NODE_USE_ENV_PROXY'             'прокси для встроенного fetch'
need 'e http_proxy= -e https_proxy='  'проверка n8n в обход прокси'
need 'remove-orphans'                 'уборка лишних контейнеров'

# Файл для ИИ-помощника должен знать текущую версию установщика,
# иначе ИИ решит, что инструкция устарела, или наоборот не заметит изменений.
V="$(grep -o '^INST_VER="[^"]*"' "$I" | cut -d'"' -f2)"
A="$ROOT/AI-HELPER.md"
if [ ! -f "$A" ]; then echo "  ПРОПАЛО: AI-HELPER.md"; fail=1
elif ! grep -q "| Версия установщика | $V |" "$A" || ! grep -q "новее, чем $V " "$A"; then
  echo "  УСТАРЕЛО: в AI-HELPER.md не версия $V - обновите шапку и раздел 0"; fail=1
fi

if [ "$fail" -ne 0 ]; then echo "  часть возможностей потерялась"; exit 1; fi
echo "  ключевые возможности на месте: $(grep -c "^need " "$0") проверок"
