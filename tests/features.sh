#!/usr/bin/env bash
# Проверяет, что важные возможности не пропали из скриптов при правках.
# Такое уже случалось: при переписывании ротации молча исчезло
# предупреждение о нехватке места.
set -Eeuo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
I="$ROOT/install.sh"
fail=0

need() {  # need "что ищем" "описание"
  grep -q -- "$1" "$I" || { echo "  ПРОПАЛО: $2"; fail=1; }
}

# уведомления
need 'Заканчивается место на диске'   'предупреждение о нехватке места'
need 'Не удалось сделать резервную копию' 'сообщение о неудачной копии'
need 'n8n не отвечает'                'тревога сторожа'
need 'n8n снова работает'             'сообщение о восстановлении'
need 'n8n обновлён'                   'сообщение об обновлении'
need 'Обновление не удалось'          'сообщение об откате'
need 'Ежемесячная сводка'             'ежемесячная сводка'
need 'n8n установлен и работает'      'сообщение об окончании установки'
need 'parse_mode=HTML'                'разметка сообщений'

# обслуживание
need 'rotate "db-"'                   'ротация копий'
need 'gunzip -t'                      'проверка копии перед восстановлением'
need 'before-restore'                 'страховочная копия перед восстановлением'
need 'update-in-progress'             'молчание сторожа во время обновления'
need 'max-size'                       'ограничение логов контейнеров'
need 'logrotate.d/n8n'                'ротация логов скриптов'
need 'NODE_USE_ENV_PROXY'             'прокси для встроенного fetch'
need 'e http_proxy= -e https_proxy='  'проверка n8n в обход прокси'
need 'remove-orphans'                 'уборка лишних контейнеров'

if [ "$fail" -ne 0 ]; then echo "  часть возможностей потерялась"; exit 1; fi
echo "  ключевые возможности на месте: 18 проверок"
